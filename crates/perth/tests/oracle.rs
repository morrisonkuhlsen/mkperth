fn perth_file(specs: &[&str]) -> String {
    let tasks: Vec<serde_json::Value> = specs
        .iter()
        .map(|s| {
            let f: Vec<&str> = s.split('|').collect();
            let deps: Vec<&str> = if f[3].is_empty() { Vec::new() } else { f[3].split(',').collect() };
            let deadline = if f[4] == "-" { serde_json::Value::Null } else { json!(f[4]) };
            json!({"id": f[0], "name": f[0], "start": f[1], "duration": f[2].parse::<i64>().unwrap(),
                   "dependencies": deps, "milestone": false, "deadline": deadline})
        })
        .collect();
    json!({"name": "oracle", "tasks": tasks, "calendar": ""}).to_string()
}

#[test]
fn perth_jl_and_mk_perth_give_the_same_dates_and_floats() {
    let date = |s: &str| Date::parse(s).unwrap();
    for (name, specs, expected) in CASES {
        let project = mkperth_perth::read(&perth_file(specs)).unwrap().project;
        let schedule = mkperth_sched::schedule(&project).unwrap();
        for line in *expected {
            let f: Vec<&str> = line.split('|').collect();
            let a = schedule.activities.iter().find(|a| a.id == f[0]).unwrap();
            let got = (a.early_start, a.early_finish, a.late_start, a.late_finish, a.total_float);
            let want = (date(f[1]), date(f[2]), date(f[3]), date(f[4]), f[5].parse::<i64>().unwrap());
            assert_eq!(got, want, "{name}: {}", f[0]);
        }
    }
}
